begin;
create extension if not exists pgtap with schema extensions;
set local search_path = public, extensions;
select plan(16);
select is((select count(*)::int from pg_enum where enumtypid='public.entity_kind'::regtype),5,'five kinds');
select ok((select bool_and(relrowsecurity) from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relname in ('workspace','workspace_member','entity','relation','type_templates','predicate_registry','audit_log','process_kind_version','process')),'RLS on all nine tables');
select ok(not has_table_privilege('authenticated','public.entity','INSERT'),'no direct entity insert');
select ok(not has_table_privilege('authenticated','public.entity','UPDATE'),'no direct entity update');
select ok(not has_table_privilege('authenticated','public.relation','DELETE'),'no direct relation delete');
select ok(not has_table_privilege('authenticated','public.audit_log','UPDATE'),'audit update denied');
select ok(not has_table_privilege('authenticated','public.audit_log','DELETE'),'audit delete denied');
select ok(not has_table_privilege('anon','public.entity','SELECT'),'anon read denied');
select ok(not has_function_privilege('anon','public.workspace_create(text,text)','EXECUTE'),'anon bootstrap denied');
select ok(has_function_privilege('authenticated','public.workspace_create(text,text)','EXECUTE'),'authenticated bootstrap allowed');
select ok(not has_function_privilege('authenticated','private.check_owner()','EXECUTE'),'private trigger helper not callable');
select ok(not has_table_privilege('service_role','public.entity','INSERT'),'service role direct insert denied');
select ok('process_kind'=any(enum_range(null::public.entity_kind)::text[]) and not ('process'=any(enum_range(null::public.entity_kind)::text[])),'Registry contains Process Kind only');
select ok(not has_table_privilege('authenticated','public.process','SELECT'),'execution reads not exposed');
select ok(not has_table_privilege('authenticated','public.process','INSERT'),'execution writes not exposed');
select ok(not has_table_privilege('authenticated','public.process_kind_version','UPDATE'),'publication writes not exposed');
select * from finish();
rollback;
